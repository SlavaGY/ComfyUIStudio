"""
errors.py
Общие исключения комплекта ComfyUI Studio для ГРАНИЦ СЕРВИСОВ (этап R11.1
плана рефакторинга).

Правила:
  * Только стандартная библиотека, без Qt -- модуль можно импортировать
    из любого процесса комплекта (Launcher, Imagine, Remote).
  * Исключения вводятся на границах: «процесс не запустился»,
    «ComfyUI недоступен». Все ``return False, "…"`` и тексты для
    пользователя по проекту НЕ переписываются; тексты ошибок остаются там,
    где они были, в UI они идут через существующий ``_tr``.
  * ``StudioError`` -- общий корень: ``except StudioError`` ловит ожидаемые
    ошибки комплекта и не ловит чужие баги (TypeError, KeyError, ...).
  * Совместимость: ``ProcessStartError`` унаследован ещё и от
    ``RuntimeError``, потому что прежний код бросал именно его и существующие
    ``except RuntimeError`` вызывающих сторон должны продолжать работать.
"""

from __future__ import annotations


class StudioError(Exception):
    """Корень ожидаемых ошибок комплекта на границах сервисов."""


class ProcessStartError(StudioError, RuntimeError):
    """Дочерний процесс (Imagine, Remote, ...) не удалось запустить:
    не хватает модулей, не найден интерпретатор и т.п. Сообщение --
    текст для пользователя."""


class ComfyUIError(StudioError):
    """Сеть/ComfyUI недоступны или ответили ошибкой -- отдаём наружу
    (в отличие от comfy_api.py в Studio, здесь это FastAPI-бэкенд, у
    которого есть кому вернуть внятный HTTP-статус вызвавшему фронтенду,
    поэтому исключение уместнее тихого None)."""


class ComfyUIConnectionError(ComfyUIError):
    """Частный случай ``ComfyUIError``: до ComfyUI не удалось достучаться
    (порт не слушает, таймаут). Отличается от ответа с ошибкой (HTTP 4xx/5xx,
    битый JSON): там ComfyUI жив, здесь -- нет. Существующие
    ``except ComfyUIError`` ловят и его."""
