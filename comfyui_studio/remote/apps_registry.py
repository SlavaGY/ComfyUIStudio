"""
Реестр "апп" терминала — этап 4 дорожной карты (`ComfyUIStudio_Remote_Roadmap.md`,
"Реестр апп + reverse-proxy на сервере", §4/§0.3).

НЕ статический список -- регистрация происходит во время запуска
процесса Remote (см. `app.py`, регистрация Imagine в `_lifespan`), а
доступность каждого приложения проверяется НА КАЖДЫЙ запрос через
`proxy_target()` -- сервер сам решает, что реально доступно прямо
сейчас (см. `GET /apps` в `routes/apps.py` и домашнюю страницу в
`routes/home.py`), а не отдаёт статический список, который тут же
разошёлся бы с реальностью, если Imagine сейчас не запущен.

Концептуально тот же паттерн, что `tool_registry.register_in_process_app()`
у desktop-окон монолитного режима -- но это ДВА РАЗНЫХ реестра, не
путать: тот -- для Qt-окон, живущих в одном процессе с лаунчером; этот
-- для веб-"апп" терминала, живущих (потенциально) в других процессах,
доступных Remote только через HTTP (см. `imagine_proxy.py`).

Один реестр на процесс Remote -- модуль-уровневый словарь, тот же
приём синглтона, что и `pairing_manager`/`hub` в соседних модулях.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional

_apps: dict[str, "RemoteApp"] = {}


@dataclass
class RemoteApp:
    id: str
    name: str
    path: str  # префикс проксирования, напр. "/apps/imagine/"
    # Возвращает "http://127.0.0.1:<port>" (без завершающего "/"), если
    # приложение прямо сейчас доступно для проксирования, иначе None --
    # вызывается заново на каждый запрос (см. list_available_apps),
    # намеренно НЕ кэшируется здесь.
    proxy_target: Callable[[], Optional[str]]
    icon: Optional[str] = None
    # НОВОЕ (этап "Запуск приложений через Remote", между этапами 6 и
    # 6.5 дорожной карты): "running" | "starting" | "stopped" -- в
    # отличие от proxy_target() (просто True/False пригодности для
    # проксирования ПРЯМО СЕЙЧАС), это даёт терминалу третье
    # промежуточное состояние ("запускается") на время, пока подпроцесс
    # уже поднят (см. app_launcher.py), но ещё не отвечает на HTTP --
    # без этого разграничения кнопка "Запустить" на телефоне не могла
    # бы показать, что запуск идёт, а не завис/не нажался.
    status_fn: Optional[Callable[[], str]] = None
    # None -- приложение зарегистрировано только для проксирования, но
    # Remote не умеет (пока) само его стартовать -- см. критерий
    # готовности нового этапа: список "поддерживаемых" приложений
    # существует независимо от того, для всех ли из них уже реализован
    # запуск с телефона.
    start_fn: Optional[Callable[[], None]] = None
    # НОВОЕ (автозапуск ComfyUI, продолжение "Запуск приложений через
    # Remote"): последняя ошибка АСИНХРОННОЙ части запуска (напр.
    # ComfyUI не поднялся за отведённое время после того, как
    # start_fn() уже вернул успех) -- см. app_launcher.imagine_last_error().
    # None, если приложение не сообщает такие ошибки отдельно от
    # исключений start_fn().
    error_fn: Optional[Callable[[], Optional[str]]] = None


def register_app(app: RemoteApp) -> None:
    _apps[app.id] = app


def get_app(app_id: str) -> Optional[RemoteApp]:
    return _apps.get(app_id)


def list_available_apps() -> list[RemoteApp]:
    """Только те приложения, чей proxy_target() СЕЙЧАС не None --
    используется там, где нужен именно факт пригодности для
    проксирования (см. imagine_proxy.py), а не полный список для
    отображения (для него см. list_all_apps() ниже)."""
    return [app for app in _apps.values() if app.proxy_target() is not None]


def list_all_apps() -> list[RemoteApp]:
    """Все зарегистрированные приложения независимо от текущего
    статуса -- НОВОЕ (этап "Запуск приложений через Remote"): раньше
    (этап 4) `GET /apps`/домашняя страница показывали ТОЛЬКО уже
    запущенные приложения (см. историю list_available_apps выше и её
    прежнее использование в routes/apps.py и routes/home.py) -- с
    телефона нельзя было даже увидеть Imagine, пока его не запустили
    вручную через Studio. Теперь список содержит все
    зарегистрированные приложения всегда, а `status_fn()` каждого
    сообщает, запущено оно, запускается или остановлено -- терминал
    сам решает, показать ссылку или кнопку "Запустить" (см.
    routes/home.py)."""
    return list(_apps.values())


def clear_registry() -> None:
    """Только для тестов (см. tests/remote/test_apps_registry.py) --
    реестр модуль-уровневый, между тестами его нужно сбрасывать, чтобы
    один тест не видел приложения, зарегистрированные другим."""
    _apps.clear()
